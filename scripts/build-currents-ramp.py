"""Write apps/web/src/currents-ramp.ts from the currents colour table (speed_m_s,r,g,b rows).

The table is forcingkit's packaged ramp (forcingkit/ramps/currents_lis.csv), copied to
apps/web/src/currents-ramp.csv. Rerun after updating that copy:

    python3 scripts/build-currents-ramp.py [path/to/currents_lis.csv]

The TypeScript carries the rows verbatim, the knots named in the table's header (the speeds the
header quotes that are also rows) and a hash of the CSV, so the two cannot drift unnoticed.
"""

import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "apps/web/src/currents-ramp.csv"
OUT = ROOT / "apps/web/src/currents-ramp.ts"

text = SRC.read_text()
comments = [ln[1:].strip() for ln in text.splitlines() if ln.startswith("#")]
rows: list[tuple[float, int, int, int]] = []
for ln in text.splitlines():
    if not ln.strip() or ln.startswith("#") or ln.startswith("speed_m_s"):
        continue
    s, r, g, b = ln.split(",")
    rows.append((float(s), int(r), int(g), int(b)))
speeds = [r[0] for r in rows]
if any(b <= a for a, b in zip(speeds, speeds[1:])):
    raise SystemExit("speeds must increase down the table")

quoted = {float(x) for x in re.findall(r"(\d+\.\d+) m/s", " ".join(comments))}
# The clamp row (the last) is the end of the table, not a knot.
knots = sorted({speeds[0]} | {q for q in quoted if any(abs(q - s) < 5e-5 for s in speeds[:-1])})

digest = hashlib.sha256(text.encode()).hexdigest()[:16]
lines = [
    "// Generated by scripts/build-currents-ramp.py from currents-ramp.csv; do not edit by hand.",
    f"// csv sha256 {digest}",
    "//",
    *[f"// {c}" for c in comments],
    "",
    "/** Currents colour table: [speed in m/s, colour] rows, interpolated in log(speed). */",
    "export const CURRENTS_RAMP: readonly [number, string][] = [",
    *[f'  [{s}, "#{r:02x}{g:02x}{b:02x}"],' for s, r, g, b in rows],
    "];",
    "",
    "/** Below this speed (m/s), the first colour. */",
    f"export const CURRENTS_FLOOR = {speeds[0]};",
    "/** Above this speed (m/s), the last colour. */",
    f"export const CURRENTS_TOP = {speeds[-1]};",
    "/** The knots named in the table's header (m/s), for the key's ticks. */",
    f"export const CURRENTS_KNOTS: readonly number[] = [{', '.join(str(k) for k in knots)}];",
    "",
]
OUT.write_text("\n".join(lines))
print(f"{OUT.relative_to(ROOT)}: {len(rows)} rows, knots {knots}")
