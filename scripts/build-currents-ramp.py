"""Write apps/web/src/currents-ramp.ts from the currents colour tables (speed_m_s,r,g,b rows).

The tables are forcingkit's packaged ramps, copied into apps/web/src: currents_lis.csv as
currents-ramp.csv (light basemap) and currents_lis_dark.csv as currents-ramp-dark.csv (dark
basemap). Rerun after updating either copy:

    python3 scripts/build-currents-ramp.py [light.csv [dark.csv]]

The TypeScript carries the rows verbatim, the knots named in the light table's header (the speeds
the header quotes that are also rows) and a hash of each CSV, so they cannot drift unnoticed. The
two tables must share their speeds, so the map swaps them by theme alone.
"""

import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WEB = ROOT / "apps/web/src"
SRC_LIGHT = Path(sys.argv[1]) if len(sys.argv) > 1 else WEB / "currents-ramp.csv"
SRC_DARK = Path(sys.argv[2]) if len(sys.argv) > 2 else WEB / "currents-ramp-dark.csv"
OUT = WEB / "currents-ramp.ts"


def read(path: Path) -> tuple[str, list[str], list[tuple[float, int, int, int]]]:
    text = path.read_text()
    comments = [ln[1:].strip() for ln in text.splitlines() if ln.startswith("#")]
    rows: list[tuple[float, int, int, int]] = []
    for ln in text.splitlines():
        if not ln.strip() or ln.startswith("#") or ln.startswith("speed_m_s"):
            continue
        s, r, g, b = ln.split(",")
        rows.append((float(s), int(r), int(g), int(b)))
    speeds = [r[0] for r in rows]
    if any(b <= a for a, b in zip(speeds, speeds[1:])):
        raise SystemExit(f"{path}: speeds must increase down the table")
    return text, comments, rows


def table(name: str, rows: list[tuple[float, int, int, int]]) -> list[str]:
    return [
        f"export const {name}: readonly [number, string][] = [",
        *[f'  [{s}, "#{r:02x}{g:02x}{b:02x}"],' for s, r, g, b in rows],
        "];",
    ]


def digest(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()[:16]


light_text, light_comments, light = read(SRC_LIGHT)
dark_text, dark_comments, dark = read(SRC_DARK)
speeds = [r[0] for r in light]
if [r[0] for r in dark] != speeds:
    raise SystemExit("the light and dark tables must have the same speeds")

quoted = {float(x) for x in re.findall(r"(\d+\.\d+) m/s", " ".join(light_comments))}
# The clamp row (the last) is the end of the table, not a knot.
knots = sorted({speeds[0]} | {q for q in quoted if any(abs(q - s) < 5e-5 for s in speeds[:-1])})
# The dark table's own description: its header up to the shared knot provenance.
dark_own = []
for c in dark_comments:
    if c.startswith("Knots"):
        break
    dark_own.append(c)

lines = [
    "// Generated by scripts/build-currents-ramp.py from currents-ramp.csv and currents-ramp-dark.csv;",
    "// do not edit by hand.",
    f"// currents-ramp.csv sha256 {digest(light_text)}; currents-ramp-dark.csv sha256 {digest(dark_text)}",
    "//",
    *[f"// {c}" for c in light_comments],
    "//",
    *[f"// {c}" for c in dark_own],
    "",
    "/** Currents colour table for the light basemap: [speed in m/s, colour] rows, interpolated in log(speed). */",
    *table("CURRENTS_RAMP", light),
    "",
    "/** Its twin for the dark basemap, on the same speeds: lightness rises with speed. */",
    *table("CURRENTS_RAMP_DARK", dark),
    "",
    "/** Below this speed (m/s), the first colour. */",
    f"export const CURRENTS_FLOOR = {speeds[0]};",
    "/** Above this speed (m/s), the last colour. */",
    f"export const CURRENTS_TOP = {speeds[-1]};",
    "/** The knots named in the table's header (m/s), for the key's ticks. */",
    f"export const CURRENTS_KNOTS: readonly number[] = [{', '.join(str(k) for k in knots)}];",
    "",
]
OUT.write_text("\n".join(lines))
print(f"{OUT.relative_to(ROOT)}: {len(light)} + {len(dark)} rows, knots {knots}")
