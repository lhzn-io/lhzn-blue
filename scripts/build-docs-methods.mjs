#!/usr/bin/env node
/**
 * Write the docs site's layer and plot pages from apps/web/src/methods.ts, the text behind every (i) on the site, so
 * the docs and the pages never drift apart. Run after editing methods.ts (Node 22.18 or later reads the .ts file
 * directly):
 *
 *     node scripts/build-docs-methods.mjs
 *
 * Writes docs/src/layers/map.md and docs/src/layers/plots.md (committed, so the docs build needs no Node). Every
 * entry in METHODS must be placed in a group below or listed in SKIP; a new entry fails the script until it is.
 * Citations ([[key]]) link to the docs' references page, numbered per entry in order of first use, as in the dialogs.
 */
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { METHODS, REF_LABELS, BUOY_SENSORS } from "../apps/web/src/methods.ts";

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SITE = "https://longhorizon.blue";

const PAGES = [
  {
    file: "docs/src/layers/map.md",
    title: "Map layers",
    intro:
      "Map layer (i) notes. Every layer covers the waterway's box, clipped to the currents model's water, so all " +
      "layers share one coastline.",
    groups: [
      ["Comfort", ["comfort", "map-comfort", "map-wat"]],
      ["Wind, waves and currents", ["map-wind", "map-waves", "map-currents", "map-radar", "current-phase"]],
      ["Satellite fields", ["map-sst", "map-chl", "map-kd490"]],
    ],
  },
  {
    file: "docs/src/layers/plots.md",
    title: "Station plots and readouts",
    intro:
      "Station plot (i) notes. \"The variable\" and \"the station\" stand for the page's selected variable and station.",
    groups: [
      ["Water quality at the buoys", ["yoy", "chg", "col", "sb", "bturb"]],
      ["Weather and waves", ["next48", "wind", "air", "pressure", "waves", "model", "advisory", "trends"]],
      ["Tides and currents", ["hilo", "dep", "mflow", "mfan", "mbins"]],
      ["Rivers", ["flow", "share", "rpct", "ryoy", "rturb"]],
      ["A point on the map", ["virtual-next48", "vwaves", "vcur", "vsst"]],
    ],
    sensors: true,
  },
];
// Entries not given a section of their own, and why.
const SKIP = { tide: "the shore stations' short form of dep (Departure from prediction)" };

const placed = new Set(PAGES.flatMap((p) => p.groups.flatMap(([, keys]) => keys)));
const missing = Object.keys(METHODS).filter((k) => !placed.has(k) && !(k in SKIP));
const unknown = [...placed].filter((k) => !METHODS[k]);
if (missing.length || unknown.length) {
  console.error(`methods.ts and this script disagree. Not placed: ${missing.join(", ") || "none"}. Not in METHODS: ${unknown.join(", ") || "none"}.`);
  process.exit(1);
}

const VARIABLE_NAMES = { temp: "temperature", salinity: "salinity", oxygen: "dissolved oxygen" };

function text(s, refs) {
  const t = s.replace(/\{variable\}/g, "the variable").replace(/\{station\}/g, "the station");
  const cap = t.charAt(0).toUpperCase() + t.slice(1);
  return cap
    .replace(/\s*\[\[([a-z0-9_]+)\]\]/g, (_, k) => {
      if (!refs.includes(k)) refs.push(k);
      return ` {ref}\`[${refs.indexOf(k) + 1}] <ref-${k}>\``;
    })
    .replace(/\*/g, "\\*");
}

function entry(key) {
  const m = METHODS[key];
  const refs = [];
  const rows = [
    ["Shows", m.shows],
    ["Method", m.method],
    ["Sensors", m.sensors],
    ["Sources", m.sources],
    ["Caveats", m.caveats],
  ].filter(([, v]) => v);
  for (const [k, v] of Object.entries(m.byVariable ?? {})) rows.push([`For ${VARIABLE_NAMES[k]}`, v]);
  let out = `(method-${key})=\n### ${m.title}\n\n`;
  out += rows.map(([label, v]) => `${label}\n: ${text(v, refs)}\n`).join("\n");
  if (m.more) out += `\n[${m.more.text}](${SITE}${m.more.href})\n`;
  if (refs.length) out += `\nReferences: ${refs.map((k, i) => `[${i + 1}] {ref}\`${REF_LABELS[k] ?? k} <ref-${k}>\``).join("; ")}.\n`;
  return out;
}

function sensors() {
  const names = { WLIS: "Western Sound", EXRX: "Execution Rocks", ARTG: "ARTG buoy", CLIS: "Central Sound" }; // stations/stations.json
  let out = "## Buoy sensors\n\nEvery sensor LISICOS lists for each buoy in its 2019 configuration {ref}`[1] <ref-lisicos>`.\n\n";
  for (const [id, s] of Object.entries(BUOY_SENSORS)) {
    out += `${names[id] ?? id} (${id})\n: ${s.platform}. Topside: ${s.topside}. Surface: ${s.surface}.`;
    if (s.mid) out += ` Mid-depth: ${s.mid}.`;
    out += ` Bottom: ${s.bottom}.\n\n`;
  }
  return out;
}

for (const page of PAGES) {
  let md = `<!-- Generated by scripts/build-docs-methods.mjs from apps/web/src/methods.ts; edit that file, not this one. -->\n\n`;
  md += `# ${page.title}\n\n${page.intro} Times are stored in UTC and labeled in New York time. All data are provisional and may be revised.\n\n`;
  for (const [heading, keys] of page.groups) md += `## ${heading}\n\n${keys.map(entry).join("\n")}\n`;
  if (page.sensors) md += sensors();
  writeFileSync(resolve(REPO, page.file), md.replace(/\n{3,}/g, "\n\n").trimEnd() + "\n", "utf8");
  console.log(`wrote ${page.file}`);
}
